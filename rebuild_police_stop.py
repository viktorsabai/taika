catalog_payload = json.loads(CATALOG_PATH.read_text())

updated_counts = {}
for course in lessons_payload.get('courses', []):
    if course.get('course_id') != 'course_l_1':
        continue
    for lesson in course.get('lessons', []):
        lid = lesson.get('lesson_id')
        spec = lesson_specs.get(lid)
        if not spec:
            continue
        lesson.update({
            'title': spec['title'],
            'subtitle': spec['subtitle'],
            'duration_minutes': spec['duration_minutes'],
            'card_count': len(spec['items']),
            'is_free': lid == 'course_l_1_l1',
            'tags': ['roadside', 'safety', 'байк', 'разговорные фразы'],
            'preview_phrase': spec['preview_phrase'],
            'content': [
                {'kind': 'intro', 'text': spec['intro']},
                {'kind': 'outline', 'text': spec['outline']},
                {'kind': 'apply', 'text': spec['apply']},
            ],
            'outcomes': [spec['outcome']],
            'prerequisites': spec['prerequisites'],
            'assistant_tips': [],
        })
        updated_counts[lid] = len(spec['items'])
    course['summary'] = {'total_lessons': 7, 'total_duration_minutes': sum(lesson.get('duration_minutes', 0) for lesson in course.get('lessons', []))}

for stepset in steps_payload.get('stepsets', []):
    lid = stepset.get('lesson_id')
    spec = lesson_specs.get(lid)
    if not spec:
        continue
    stepset['hints'] = spec['hints']
    stepset['items'] = spec['items']

