def item(order, kind, **kwargs):
    out = {"order": order, "kind": kind}
    if kind in ("word", "phrase", "casual"):
        out["ru"] = kwargs.get("ru", "")
        out["thai"] = kwargs.get("thai", "")
        out["phonetic"] = kwargs.get("phonetic", "")
        if kwargs.get("tip"):
            out["tip"] = kwargs["tip"]
    elif kind == "tip":
        out["text"] = kwargs.get("text", "")
    return out


