def main():
    new_courses = make_courses()
    new_lessons_root = make_lessons()
    new_lessons_by_id = {c["course_id"]: c for c in new_lessons_root["courses"]}
    new_steps = make_steps()

    # taika_basa_course.json
    with open(COURSE_PATH, "r", encoding="utf-8") as f:
        course_list = json.load(f)
    for new_c in new_courses:
        for i, c in enumerate(course_list):
            if c.get("id") == new_c["id"]:
                course_list[i] = new_c
                break
    with open(COURSE_PATH, "w", encoding="utf-8") as f:
        json.dump(course_list, f, ensure_ascii=False, indent=2)

    # lessons.json
    with open(LESSONS_PATH, "r", encoding="utf-8") as f:
        lessons_data = json.load(f)
    for i, c in enumerate(lessons_data["courses"]):
        if c.get("course_id") in WAVE_IDS:
            lessons_data["courses"][i] = new_lessons_by_id[c["course_id"]]
    with open(LESSONS_PATH, "w", encoding="utf-8") as f:
        json.dump(lessons_data, f, ensure_ascii=False, indent=2)

    # steps.json — порядок: База → Жизнь → На одной волне → Тайский для души
    with open(STEPS_PATH, "r", encoding="utf-8") as f:
        steps_data = json.load(f)
    base_steps = [s for s in steps_data["stepsets"] if (s.get("course_id") or "").startswith("course_b_")]
    life_steps = [s for s in steps_data["stepsets"] if (s.get("course_id") or "").startswith("course_l_")]
    soul_steps = [s for s in steps_data["stepsets"] if (s.get("course_id") or "").startswith("course_s_")]
    steps_data["stepsets"] = base_steps + life_steps + new_steps["stepsets"] + soul_steps
    with open(STEPS_PATH, "w", encoding="utf-8") as f:
        json.dump(steps_data, f, ensure_ascii=False, indent=2)

    print("Обновлены базовые файлы: На одной волне (6 курсов)")
    print("  ", COURSE_PATH)
    print("  ", LESSONS_PATH)
    print("  ", STEPS_PATH)
    print("Уроков:", sum(len(c["lessons"]) for c in new_lessons_root["courses"]), "| Stepsets:", len(new_steps["stepsets"]))


if __name__ == "__main__":
    main()
