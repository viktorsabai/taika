def make_lessons():
    config = get_lessons_config()
    course_titles = {c["id"]: c["title"] for c in make_courses()}
    courses_out = []
    for cid in ["course_long_" + str(i) for i in range(1, 8)]:
        less = []
        for i, (lid, title, subtitle, preview, card_count) in enumerate(config[cid], 1):
            preview_clean = preview.replace("\u0301", "")
            less.append({
                "lesson_id": lid,
                "order": i,
                "title": title,
                "subtitle": subtitle,
                "duration_minutes": 3 if i <= 2 else 4,
                "card_count": card_count,
                "is_free": i <= 2,
                "tags": [],
                "preview_phrase": preview_clean,
                "content": [{"kind": "intro", "text": ""}, {"kind": "outline", "text": ""}, {"kind": "apply", "text": ""}],
                "outcomes": [],
                "prerequisites": [config[cid][i - 2][0]] if i >= 2 else [],
                "links": {"steps_ref": lid + "_steps", "hometask_ref": lid + "_home"},
                "assistant_tips": [],
            })
        total_mins = sum(l.get("duration_minutes", 3) for l in less)
        courses_out.append({"course_id": cid, "course_title": course_titles[cid], "lessons": less, "summary": {"total_lessons": len(less), "total_duration_minutes": total_mins}})
    return {"version": 1, "courses": courses_out}


