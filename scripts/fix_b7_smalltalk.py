def tip(order: int, text: str, extra: str | None = None) -> dict:
    row = {"order": order, "kind": "tip", "text": text}
    if extra:
        row["tip"] = extra
    return row


def card(order: int, kind: str, ru: str, thai: str, phonetic: str, tip_text: str) -> dict:
    return {
        "order": order,
        "kind": kind,
        "ru": ru,
        "thai": thai,
        "phonetic": phonetic,
        "tip": tip_text,
    }


