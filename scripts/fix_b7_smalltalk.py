def apply() -> None:
    steps = json.loads(STEPS.read_text(encoding="utf-8"))
    lessons = json.loads(LESSONS.read_text(encoding="utf-8"))
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))

    spec_by_id = {s["lesson_id"]: s for s in LESSONS_SPEC}

    for ss in steps["stepsets"]:
        spec = spec_by_id.get(ss.get("lesson_id") or "")
        if not spec:
            continue
        ss["hints"] = list(spec["hints"])
        ss["items"] = deepcopy(spec["items"])

    for block in lessons["courses"]:
        if block.get("course_id") != "course_b_7":
            continue
        block["course_title"] = COURSE_TITLE
        block["description"] = COURSE_DESC
        for lesson in block.get("lessons") or []:
            spec = spec_by_id[lesson["lesson_id"]]
            n = len(spec["items"])
            lesson["title"] = spec["title"]
            lesson["subtitle"] = spec["subtitle"]
            lesson["preview_phrase"] = spec["preview"]
            lesson["card_count"] = n
            lesson["duration_minutes"] = 4
            lesson["content"] = [
                {"kind": "intro", "text": spec["intro"]},
                {"kind": "outline", "text": spec["outline"]},
                {"kind": "apply", "text": spec["apply"]},
            ]
            lesson["outcomes"] = [spec["outcome"]]
        block["summary"] = {
            "total_lessons": 6,
            "total_duration_minutes": 24,
        }

    for course in catalog:
        if course.get("id") != "course_b_7":
            continue
        course["title"] = COURSE_TITLE
        course["description"] = COURSE_DESC
        course["short_description"] = COURSE_SHORT
        course["lesson_count"] = 6
        course["duration_minutes"] = 24
        course["learning_outcomes"] = [
            {"type": "Смолток", "count": 6},
            {"type": "Живые реплики", "count": 36},
        ]

    STEPS.write_text(json.dumps(steps, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    LESSONS.write_text(json.dumps(lessons, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    CATALOG.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("course_b_7 rewritten as small-talk capstone")


if __name__ == "__main__":
    apply()
