@pytest.mark.parametrize("th,want", sorted(GOLD.items()))
def test_gold_readings(th, want):
    got = tl.word_letters(th)
    assert got is not None, th
    assert "-".join(got) == want, (th, got)


def test_toned_word_uses_spoken_syllables():
    assert q.engine_phonetic("โทรศัพท์") == "то→-ра↑-сап↓"
    assert q.engine_phonetic("ขนม") == "кха↓-ном↗"
    assert q.engine_phonetic("ครับ") == "кхрап↑"
    assert q.engine_phonetic("คะ") == "кха↑"
    assert q.engine_phonetic("ค่ะ") == "кха↘"


def test_without_w2p_simple_words_still_read(monkeypatch):
    """Нет модели произношения — слова с явной гласной читаются по написанию, не падаем."""
    monkeypatch.setattr(tl, "_w2p", lambda: None)
    tl.spoken_syllables.cache_clear()
    tl.word_reading.cache_clear()
    try:
        assert tl.word_letters("สอง") == ["сонг"]
        assert tl.word_letters("ห้องน้ำ") == ["хонг", "нам"]
        assert tl.word_letters("ไม่เป็นไร") == ["май", "пен", "рай"]
    finally:
        tl.spoken_syllables.cache_clear()
        tl.word_reading.cache_clear()


def test_unreadable_word_returns_none():
    assert tl.word_letters("") is None
    assert tl.word_letters("abc") is None
