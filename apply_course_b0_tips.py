steps_path = ROOT / 'steps.json'
lessons_path = ROOT / 'lessons.json'
steps = json.loads(steps_path.read_text(encoding='utf-8'))
lessons = json.loads(lessons_path.read_text(encoding='utf-8'))

stepsets = {s['lesson_id']: s for s in steps['stepsets']}
for lesson_id, tips in LESSON_TIPS.items():
    if lesson_id not in stepsets:
        raise KeyError(f'Missing stepset: {lesson_id}')
    stepsets[lesson_id]['items'] = [
        {'order': i, 'kind': 'tip', 'tip': title, 'text': text}
        for i, (title, text) in enumerate(tips, start=1)
    ]

for course in lessons['courses']:
    if course['course_id'] != 'course_b_0':
        continue
    for lesson in course['lessons']:
        if lesson['lesson_id'] in LESSON_TIPS:
            lesson['card_count'] = len(LESSON_TIPS[lesson['lesson_id']])

steps_path.write_text(json.dumps(steps, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
lessons_path.write_text(json.dumps(lessons, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print('updated lessons:', {k: len(v) for k,v in LESSON_TIPS.items()})
