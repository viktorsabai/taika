lessons_payload=json.loads(LESSONS.read_text())
steps_payload=json.loads(STEPS.read_text())
catalog_payload=json.loads(CATALOG.read_text())
step_map={s['lesson_id']:s for s in steps_payload['stepsets']}
updated=[]
for course in lessons_payload['courses']:
    cid=course.get('course_id')
    if cid not in SPECS:
        continue
    spec=SPECS[cid]
    course['description']=spec['description']
    course['summary']={'total_lessons':len(course.get('lessons',[])), 'total_duration_minutes':sum(l.get('duration_minutes',4) for l in course.get('lessons',[]))}
    course['prerequisites']=course.get('prerequisites', ['course_b_1'])
    lesson_specs=spec['lessons']
    for lesson, values in zip(course.get('lessons',[]), lesson_specs):
        title, subtitle, outcome, outline = values
        lesson.update({
          'title':title,
          'subtitle':subtitle,
          'duration_minutes':max(4, lesson.get('duration_minutes',4)),
          'tags':spec['tags'],
          'content':[
             {'kind':'intro','text':f"Кун Кру проведёт сцену «{title}»: {subtitle.lower()}."},
             {'kind':'outline','text':outline},
             {'kind':'apply','text':f"Проговори сцену «{title}» и представь один реальный диалог в Таиланде; цель — выбрать фразу в правильный момент."},
          ],
          'outcomes':[outcome],
          'assistant_tips':[],
        })
        lid=lesson['lesson_id']
        step=step_map.get(lid)
        if not step:
            continue
        # Keep existing language cards, but ensure each lesson starts with a course-specific tip.
        existing=step.get('items',[])
        if existing and existing[0].get('kind')=='tip':
            existing[0]['text']=f"Контекст «{title}»: {outline}"
        else:
            existing.insert(0, {'kind':'tip','text':f"Контекст «{title}»: {outline}",'order':1})
            for i,item in enumerate(existing,1): item['order']=i
        step['items']=existing
        step['hints']=[f"Сначала держи в голове сцену «{title}», потом выбирай короткую фразу; не смешивай её с соседним этапом."]
        lesson['card_count']=len(existing)
        updated.append(lid)

